const DICTS: Record<Lang, Dict> = { es: ES, en: EN };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string };
const I18nCtx = createContext<Ctx>({ lang: "es", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  // Always start as "es" on both server and first client render to avoid hydration mismatches.
  const [lang, setLangState] = useState<Lang>("es");
  const [hydrated, setHydrated] = useState(false);
  useEffect(() => {
    const saved = typeof window !== "undefined" ? localStorage.getItem("citygo.lang") : null;
    if (saved === "en" || saved === "es") setLangState(saved as Lang);
    setHydrated(true);
  }, []);
  useEffect(() => {
    if (hydrated && typeof window !== "undefined") localStorage.setItem("citygo.lang", lang);
  }, [lang, hydrated]);
  const t = (key: string) => DICTS[lang][key] ?? DICTS.es[key] ?? key;
  return <I18nCtx.Provider value={{ lang, setLang: setLangState, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);

